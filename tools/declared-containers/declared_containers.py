#!/usr/bin/env python3
"""Generate the containers tn/ declares, as a node-exporter textfile (needs PyYAML).

    python3 tools/declared-containers/declared_containers.py          # write the .prom file
    python3 tools/declared-containers/declared_containers.py --check  # fail if it is stale (validate.py)

ContainerDown (alerting-rules.yml) fires for a declared container that is not running, so a
Stack or Service removed from git stops being expected as soon as this file is redeployed.
Edit the Compose files and rerun this; never edit the output.
"""
import argparse
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "tn/monitoring/node-exporter/declared_containers.prom"
METRIC = "homeops_container_declared"
HEADER = (f"# HELP {METRIC} A container that tn/ declares, and so should be running. "
          "Generated by tools/declared-containers; do not edit.\n"
          f"# TYPE {METRIC} gauge\n")
VARIABLE = re.compile(r"\$\{?[A-Za-z_]")


class GeneratorError(Exception):
    pass


def compose_files(entry: Path) -> list[Path]:
    """A Stack's entry file plus everything it includes, recursively (as validate.py reads them)."""
    seen: list[Path] = []
    todo = [entry]
    while todo:
        f = todo.pop()
        if f in seen:
            continue
        seen.append(f)
        for inc in (yaml.safe_load(f.read_text()) or {}).get("include") or []:
            paths = inc.get("path") if isinstance(inc, dict) else inc
            todo += [(f.parent / p).resolve() for p in ([paths] if isinstance(paths, str) else paths or [])]
    return seen


def labels_of(service: dict) -> dict:
    labels = service.get("labels") or {}
    if isinstance(labels, list):
        labels = dict(item.split("=", 1) if "=" in item else (item, "") for item in labels)
    return {k: str(v) for k, v in labels.items()}


def declared(root: Path) -> list[tuple[str, str, str, str]]:
    """(stack, service, container name, tier) for every Service doco-cd deploys from tn/<stack>/compose.yaml."""
    rows, problems = [], []
    for entry in sorted((root / "tn").glob("*/compose.yaml")):
        # doco-cd uses the folder name as the Compose project name (.doco-cd.yml).
        stack = entry.parent.name
        for f in compose_files(entry):
            for service, spec in ((yaml.safe_load(f.read_text()) or {}).get("services") or {}).items():
                spec = spec or {}
                name = str(spec.get("container_name") or f"{stack}-{service}-1")
                tier = labels_of(spec).get("tier", "")
                where = f"{f.relative_to(root)}: {service}"
                if VARIABLE.search(name):
                    problems.append(f"{where}: container_name {name!r} must not use variables")
                if not tier or VARIABLE.search(tier):
                    problems.append(f"{where}: no tier label (or it uses variables)")
                rows.append((stack, service, name, tier))
    if problems:
        raise GeneratorError("\n".join(problems))
    return sorted(rows)


def render(root: Path = ROOT) -> str:
    return HEADER + "".join(f'{METRIC}{{stack="{s}",service="{v}",name="{n}",tier="{t}"}} 1\n'
                            for s, v, n, t in declared(root))


def main(argv=None):
    parser = argparse.ArgumentParser(description="Generate the containers tn/ declares, for ContainerDown.")
    parser.add_argument("--check", action="store_true", help="fail if --out is stale")
    parser.add_argument("--root", type=Path, default=ROOT, help=f"repository root (default: {ROOT})")
    parser.add_argument("--out", type=Path, help=f"output file (default: {OUT.relative_to(ROOT)} under --root)")
    args = parser.parse_args(argv)
    out = args.out or args.root / OUT.relative_to(ROOT)
    try:
        text = render(args.root)
    except GeneratorError as exc:
        print(exc)
        return 1
    if args.check:
        if not out.exists() or out.read_text() != text:
            print(f"{out}: stale; run python3 tools/declared-containers/declared_containers.py")
            return 1
        return 0
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
