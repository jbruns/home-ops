"""Tests for the declared-containers generator, at its render() and CLI seams."""
import subprocess
import sys
import textwrap
from pathlib import Path

import pytest

TOOL_DIR = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(TOOL_DIR))

import declared_containers  # noqa: E402

FIXTURE = {
    "tn/_baseline.yaml": """
        services:
          baseline:
            restart: unless-stopped
    """,
    "tn/edge/compose.yaml": """
        services:
          traefik:
            extends: {file: ../_baseline.yaml, service: baseline}
            container_name: traefik
            labels:
              tier: critical
              startup-order: "0"
    """,
    "tn/app/compose.yaml": """
        include:
          - ./web/service.yaml
          - path: [./db/service.yaml]
    """,
    "tn/app/web/service.yaml": """
        services:
          web:
            labels: ["tier=warning", "startup-order=2"]
          web-exporter:
            container_name: web-exporter
            labels: {tier: info}
    """,
    "tn/app/db/service.yaml": """
        services:
          db:
            container_name: app-db
            labels: {tier: "critical"}
    """,
}

EXPECTED = """\
# HELP homeops_container_declared A Service that tn/ declares, whose container should be running. Generated by tools/declared-containers; do not edit.
# TYPE homeops_container_declared gauge
homeops_container_declared{stack="app",service="db",name="app-db",tier="critical"} 1
homeops_container_declared{stack="app",service="web",name="app-web-1",tier="warning"} 1
homeops_container_declared{stack="app",service="web-exporter",name="web-exporter",tier="info"} 1
homeops_container_declared{stack="edge",service="traefik",name="traefik",tier="critical"} 1
"""


def write(root: Path, files: dict[str, str]) -> None:
    for rel, text in files.items():
        p = root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(textwrap.dedent(text).lstrip("\n"))


def run(*args: str) -> subprocess.CompletedProcess:
    return subprocess.run([sys.executable, str(TOOL_DIR / "declared_containers.py"), *args],
                          capture_output=True, text=True)


@pytest.fixture
def root(tmp_path):
    write(tmp_path, FIXTURE)
    return tmp_path


def test_render_lists_every_service_of_every_stack(root):
    assert declared_containers.render(root) == EXPECTED


def test_a_retired_stack_or_removed_service_is_no_longer_declared(root):
    (root / "tn/edge/compose.yaml").unlink()
    write(root, {"tn/app/web/service.yaml": "services:\n  web:\n    labels: {tier: warning}\n"})
    text = declared_containers.render(root)
    assert 'stack="edge"' not in text and 'service="web-exporter"' not in text
    assert 'service="web"' in text


@pytest.mark.parametrize("service, problem", [
    ("web:\n    container_name: ${NAME}\n    labels: {tier: info}", "web: container_name"),
    ("web:\n    labels: {tier: info, other: x}\n    image: x\n  bare:\n    image: y", "bare: no tier label"),
])
def test_render_rejects_what_it_cannot_resolve(root, service, problem):
    write(root, {"tn/app/web/service.yaml": "services:\n  " + service + "\n"})
    with pytest.raises(declared_containers.GeneratorError, match=problem):
        declared_containers.render(root)


def test_render_rejects_a_missing_include(root):
    (root / "tn/app/web/service.yaml").unlink()
    with pytest.raises(declared_containers.GeneratorError, match="includes missing .*web/service.yaml"):
        declared_containers.render(root)


def test_check_reports_a_stale_file_and_write_fixes_it(root):
    out = root / "declared.prom"
    r = run("--root", str(root), "--out", str(out), "--check")
    assert r.returncode == 1 and "stale" in r.stdout
    assert run("--root", str(root), "--out", str(out)).returncode == 0
    assert out.read_text() == EXPECTED
    assert run("--root", str(root), "--out", str(out), "--check").returncode == 0


def test_committed_file_is_current():
    r = run("--check")
    assert r.returncode == 0, r.stdout
